      ? label(key.name)
      : '${label(key.name)} ${key.symbols}';

  String sheetTitle(String title) =>
      title == 'Untitled Composition' ? label(title) : title;

  String noteName(String name) {
    if (localeName != 'es') return name;
    const solfege = {
      'C': 'Do',
      'D': 'Re',
      'E': 'Mi',
      'F': 'Fa',
      'G': 'Sol',
      'A': 'La',
      'B': 'Si',
    };
    return name.isEmpty
        ? name
        : '${solfege[name[0]] ?? name[0]}${name.substring(1)}';
  }
